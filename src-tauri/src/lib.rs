pub fn export_bindings(builder: &tauri_specta::Builder<tauri::Wry>) {
    let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../src/lib/ipc.ts");
    builder
        .export(
            specta_typescript::Typescript::default()
                .header("// Generated by tauri-specta. Do not edit.\n"),
            path,
        )
        .expect("export TypeScript bindings");
}

/// Prunes history past the retention window at startup and then daily.
fn spawn_retention(history: Arc<history::History>, days: u32) {
    tauri::async_runtime::spawn(async move {
        loop {
            match history.prune(days, history::now_ms()) {
                Ok(0) => {}
                Ok(n) => log::info!("pruned {n} history items older than {days} days"),
                Err(e) => log::warn!("{e}"),
            }
            tokio::time::sleep(std::time::Duration::from_secs(24 * 3600)).await;
        }
    });
}

#[cfg_attr(mobile, tauri::mobile_entry_point)]
pub fn run() {
    let builder = specta_builder();
    #[cfg(debug_assertions)]
    export_bindings(&builder);

    tauri::Builder::default()
        // Must be first: a second launch focuses the Hub and exits.
        .plugin(tauri_plugin_single_instance::init(|app, _args, _cwd| {
            overlay::open_hub(app);
        }))
        .plugin(tauri_plugin_autostart::init(
            tauri_plugin_autostart::MacosLauncher::LaunchAgent,
            Some(vec!["--autostart"]),
        ))
        .plugin(tauri_plugin_opener::init())
        .plugin(
            tauri_plugin_log::Builder::new()
                .clear_targets()
                .target(tauri_plugin_log::Target::new(
                    tauri_plugin_log::TargetKind::LogDir {
                        file_name: Some("burbuja".into()),
                    },
                ))
                .target(tauri_plugin_log::Target::new(
                    tauri_plugin_log::TargetKind::Stdout,
                ))
                .level(log::LevelFilter::Info)
                .level_for(
                    "burbuja_lib",
                    if cfg!(debug_assertions) {
                        log::LevelFilter::Debug
                    } else {
                        log::LevelFilter::Info
                    },
                )
                .max_file_size(1_000_000)
                .rotation_strategy(tauri_plugin_log::RotationStrategy::KeepSome(5))
                .build(),
        )
        .plugin(tauri_plugin_store::Builder::default().build())
        .invoke_handler(builder.invoke_handler())
        .on_menu_event(|app, event| match event.id().as_ref() {
            overlay::MENU_HIDE_HOUR => overlay::hide_idle_for_an_hour(app),
            overlay::MENU_SETTINGS => overlay::open_hub(app),
            other => tray::on_menu(app, other),
        })
        // Closing the Hub hides it; Burbuja keeps running in the tray.
        .on_window_event(|window, event| {
            if window.label() == "hub"
                && let tauri::WindowEvent::CloseRequested { api, .. } = event
            {
                api.prevent_close();
                let _ = window.hide();
            }
        })
        .setup(move |app| {
            builder.mount_events(app);

            let overlay_state = Arc::new(overlay::OverlayState::default());
            app.manage(Arc::clone(&overlay_state));

            let settings = settings::load(app.handle());
            let sounds = SoundPlayer::spawn(settings.sound_volume);
            let status_app = app.handle().clone();
            let engine = EngineHost::new(
                commands::engine_config(app.handle(), &settings),
                Box::new(move |status| {
                    let _ = events::EngineStatusChanged(status).emit(&status_app);
                }),
            );
            // Load + warm up in the background so the first dictation is fast.
            let preload = Arc::clone(&engine);
            tauri::async_runtime::spawn(async move { preload.preload().await });

            let data_dir = app.path().app_data_dir()?;
            let history = Arc::new(
                history::History::open(&data_dir.join("history.db"))
                    .or_else(|e| {
                        log::error!("{e}; keeping history in memory for this session");
                        history::History::in_memory()
                    })
                    .map_err(|e| e.to_string())?,
            );
            spawn_retention(Arc::clone(&history), settings.history_retention_days);

            let controller = dictation::controller::spawn(
                app.handle().clone(),
                sounds.clone(),
                settings.clone(),
                Arc::clone(&engine),
                Arc::clone(&history),
            );

            let spec = HotkeySpec::parse(&settings.hotkey)
                .or_else(|_| HotkeySpec::parse(settings::default_hotkey()))
                .expect("default hotkey parses");
            let tray_hotkey = spec.display(core::hotkey_spec::Platform::current());
            let sink_controller = controller.clone();
            let hotkeys = HotkeyService::spawn(
                spec,
                Box::new(move |binding, event, at| {
                    // The tray's "Enabled" toggle; Esc still reaches an in-flight dictation.
                    if tray::ENABLED.load(std::sync::atomic::Ordering::SeqCst)
                        || event == core::hotkey_spec::HotkeyEvent::Escape
                    {
                        sink_controller.send(dictation::Msg::Hotkey { binding, event, at });
                    }
                }),
            )
            .map_err(|e| log::error!("global hotkey unavailable: {e}"))
            .ok();

            match tray::create(
                app.handle(),
                tray::is_spanish(settings.ui_language),
                &tray_hotkey,
            ) {
                Ok(t) => {
                    app.manage(t);
                }
                Err(e) => log::error!("tray unavailable: {e}"),
            }
            let tray_app = app.handle().clone();
            events::DictationState::listen(app, move |e| {
                if let Some(t) = tray_app.try_state::<tray::Tray>() {
                    let recording = matches!(
                        e.payload.state,
                        events::UiState::Listening | events::UiState::HandsFree
                    );
                    t.set_recording(recording);
                }
            });
            app.manage(AppState {
                settings: Mutex::new(settings),
                controller,
                sounds,
                hotkeys,
                preview: Mutex::new(None),
                engine,
                downloads: Default::default(),
                history,
            });

            // Windows come last: their first commands need AppState, and a webview created
            // earlier could call them before it's managed (the Hub then stayed black).
            if let Err(e) = overlay::create_bubble(app.handle()) {
                log::error!("could not create the bubble window: {e}");
            }
            overlay::spawn_hover_watch(app.handle().clone(), overlay_state);
            // Launched by autostart: stay in the tray (the Hub opens from there).
            let autostart = std::env::args().any(|a| a == "--autostart");
            let hub_config = app
                .config()
                .app
                .windows
                .iter()
                .find(|w| w.label == "hub")
                .cloned()
                .ok_or("no hub window in tauri.conf.json")?;
            tauri::WebviewWindowBuilder::from_config(app.handle(), &hub_config)?
                .visible(!autostart)
                .build()?;

            log::info!("Burbuja {} ready", app.package_info().version);
            Ok(())
        })
        .run(tauri::generate_context!())
        .expect("error while running Burbuja");
}
